/*
 * Clock and reset IDs for the Broadcom BCMRING chip-control block ("chipc").
 *
 * IDs 0..21 are the vendor's chipcHw_CLOCK_e values (the first argument of
 * chipcHw_setClockFrequency() and the csp_id field of the vendor struct
 * clk).
 */
#ifndef _DT_BINDINGS_CLOCK_BRCM_BCMRING_CHIPC_H
#define _DT_BINDINGS_CLOCK_BRCM_BCMRING_CHIPC_H

/* PLL1 channels */
#define BCMRING_CLK_DDR		0
#define BCMRING_CLK_ARM		1
#define BCMRING_CLK_ESW		2
#define BCMRING_CLK_VPM		3
#define BCMRING_CLK_ESW125	4
#define BCMRING_CLK_UART	5
#define BCMRING_CLK_SDIO0	6
#define BCMRING_CLK_SDIO1	7
#define BCMRING_CLK_SPI		8
#define BCMRING_CLK_ETM		9
/* divider clocks */
#define BCMRING_CLK_BUS		10	/* "ACLK" */
#define BCMRING_CLK_OTP		11
#define BCMRING_CLK_I2C		12
#define BCMRING_CLK_I2S0	13
#define BCMRING_CLK_RTBUS	14
#define BCMRING_CLK_APM100	15
#define BCMRING_CLK_TSC		16
#define BCMRING_CLK_LED		17
/* PLL2 channels */
#define BCMRING_CLK_USB		18
#define BCMRING_CLK_LCD		19
#define BCMRING_CLK_APM		20	/* "APM200" */
/* divider clock */
#define BCMRING_CLK_I2S1	21

/* PLL VCOs */
#define BCMRING_CLK_PLL1	22
#define BCMRING_CLK_PLL2	23

/* Bus-interface gates: bit n of the BusIntfClock register (offset 0x5c) */
#define BCMRING_CLK_BUSIF(n)	(32 + (n))
#define BCMRING_CLK_BUSIF_ARM	BCMRING_CLK_BUSIF(0)
#define BCMRING_CLK_BUSIF_VDEC	BCMRING_CLK_BUSIF(1)
#define BCMRING_CLK_BUSIF_ARAM	BCMRING_CLK_BUSIF(2)
#define BCMRING_CLK_BUSIF_HPM	BCMRING_CLK_BUSIF(3)
#define BCMRING_CLK_BUSIF_DDRC	BCMRING_CLK_BUSIF(4)
#define BCMRING_CLK_BUSIF_DMAC0	BCMRING_CLK_BUSIF(5)
#define BCMRING_CLK_BUSIF_DMAC1	BCMRING_CLK_BUSIF(6)
#define BCMRING_CLK_BUSIF_NVI	BCMRING_CLK_BUSIF(7)
#define BCMRING_CLK_BUSIF_ESW	BCMRING_CLK_BUSIF(8)
#define BCMRING_CLK_BUSIF_GE	BCMRING_CLK_BUSIF(9)
#define BCMRING_CLK_BUSIF_I2CH	BCMRING_CLK_BUSIF(10)
#define BCMRING_CLK_BUSIF_I2S0	BCMRING_CLK_BUSIF(11)
#define BCMRING_CLK_BUSIF_I2S1	BCMRING_CLK_BUSIF(12)
#define BCMRING_CLK_BUSIF_VRAM	BCMRING_CLK_BUSIF(13)
#define BCMRING_CLK_BUSIF_CLCD	BCMRING_CLK_BUSIF(14)
#define BCMRING_CLK_BUSIF_LDK	BCMRING_CLK_BUSIF(15)
#define BCMRING_CLK_BUSIF_LED	BCMRING_CLK_BUSIF(16)
#define BCMRING_CLK_BUSIF_OTP	BCMRING_CLK_BUSIF(17)
#define BCMRING_CLK_BUSIF_PIF	BCMRING_CLK_BUSIF(18)
#define BCMRING_CLK_BUSIF_SPU	BCMRING_CLK_BUSIF(19)
#define BCMRING_CLK_BUSIF_SDIO0	BCMRING_CLK_BUSIF(20)
#define BCMRING_CLK_BUSIF_SDIO1	BCMRING_CLK_BUSIF(21)
#define BCMRING_CLK_BUSIF_SPIH	BCMRING_CLK_BUSIF(22)
#define BCMRING_CLK_BUSIF_SPIS	BCMRING_CLK_BUSIF(23)
#define BCMRING_CLK_BUSIF_UART0	BCMRING_CLK_BUSIF(24)
#define BCMRING_CLK_BUSIF_UART1	BCMRING_CLK_BUSIF(25)
#define BCMRING_CLK_BUSIF_BBL	BCMRING_CLK_BUSIF(26)
#define BCMRING_CLK_BUSIF_I2CS	BCMRING_CLK_BUSIF(27)
#define BCMRING_CLK_BUSIF_USBH	BCMRING_CLK_BUSIF(28)
#define BCMRING_CLK_BUSIF_USBD	BCMRING_CLK_BUSIF(29)
#define BCMRING_CLK_BUSIF_BROM	BCMRING_CLK_BUSIF(30)
#define BCMRING_CLK_BUSIF_TSC	BCMRING_CLK_BUSIF(31)

#define BCMRING_NUM_CLKS	64

/*
 * Resets: bit n of the 64-bit {SoftReset2 (0x84), SoftReset1 (0x80)} pair.
 * IDs 0..3 (chip soft, chip warm, ARM, ARM hold) and 60..63 (unhold
 * requests) are refused by the driver.
 */
#define BCMRING_RST_ETM		4
#define BCMRING_RST_TMR		5
#define BCMRING_RST_WDOG	6
#define BCMRING_RST_NVI		7
#define BCMRING_RST_UART0	8
#define BCMRING_RST_UART1	9
#define BCMRING_RST_GPIO0	10
#define BCMRING_RST_GPIO1	11
#define BCMRING_RST_SPIH	12
#define BCMRING_RST_SPIS	13
#define BCMRING_RST_I2S0	14
#define BCMRING_RST_I2S1	15
#define BCMRING_RST_BBL		16
#define BCMRING_RST_SDIO0	17
#define BCMRING_RST_SDIO1	18
#define BCMRING_RST_I2CH	19
#define BCMRING_RST_I2CS	20
#define BCMRING_RST_PIF		21
#define BCMRING_RST_LCD		22
#define BCMRING_RST_PKA		23
#define BCMRING_RST_RNG		24
#define BCMRING_RST_SPU		25
#define BCMRING_RST_LED		26
#define BCMRING_RST_KEYPAD	27
#define BCMRING_RST_VPM		28
#define BCMRING_RST_VPM_GLOBAL	29
#define BCMRING_RST_VPM_HOLD	30
#define BCMRING_RST_VPM_GLOBAL_HOLD 31
#define BCMRING_RST_APM		32	/* vendor mask also sets bit 45 */
#define BCMRING_RST_PCM		33
#define BCMRING_RST_TSC		34
#define BCMRING_RST_DDR		35
#define BCMRING_RST_DDRPHY	36
#define BCMRING_RST_ESWCLK	37
#define BCMRING_RST_ESW		38
#define BCMRING_RST_USB		39
#define BCMRING_RST_USB1	40
#define BCMRING_RST_USB2	41
#define BCMRING_RST_OTP		42
#define BCMRING_RST_GE		43
#define BCMRING_RST_VDEC	44
#define BCMRING_RST_APM2	45	/* second bit of the vendor APM mask */

#define BCMRING_NUM_RESETS	60

#endif
